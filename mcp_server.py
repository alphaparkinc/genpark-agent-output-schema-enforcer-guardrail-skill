import sys
import json
from client import OutputSchemaEnforcer

def handle_request(req):
    method = req.get("method")
    req_id = req.get("id")
    
    if method == "initialize":
        return {
            "jsonrpc": "2.0",
            "id": req_id,
            "result": {
                "protocolVersion": "2024-11-05",
                "capabilities": {"tools": {}},
                "serverInfo": {"name": "genpark-agent-output-schema-enforcer-guardrail-skill", "version": "1.0.0"}
            }
        }
    elif method == "tools/list":
        return {
            "jsonrpc": "2.0",
            "id": req_id,
            "result": {
                "tools": [
                    {
                        "name": "enforce_output_schema",
                        "description": "Repair malformed JSON and validate schema fields",
                        "inputSchema": {
                            "type": "object",
                            "properties": {
                                "raw_json_str": {"type": "string", "description": "Raw JSON string from model"},
                                "required_fields": {"type": "array", "items": {"type": "string"}, "description": "Required keys"}
                            },
                            "required": ["raw_json_str"]
                        }
                    }
                ]
            }
        }
    elif method == "tools/call":
        params = req.get("params", {})
        tool_name = params.get("name")
        args = params.get("arguments", {})
        
        if tool_name == "enforce_output_schema":
            raw = args.get("raw_json_str", "")
            req_f = args.get("required_fields", [])
            res = OutputSchemaEnforcer.repair_and_validate(raw, req_f)
            return {
                "jsonrpc": "2.0",
                "id": req_id,
                "result": {
                    "content": [{"type": "text", "text": json.dumps(res)}]
                }
            }
    return {"jsonrpc": "2.0", "id": req_id, "error": {"code": -32601, "message": "Method not found"}}

def main():
    for line in sys.stdin:
        if not line.strip():
            continue
        try:
            req = json.loads(line)
            res = handle_request(req)
            sys.stdout.write(json.dumps(res) + "\n")
            sys.stdout.flush()
        except Exception as e:
            err = {"jsonrpc": "2.0", "id": None, "error": {"code": -32700, "message": str(e)}}
            sys.stdout.write(json.dumps(err) + "\n")
            sys.stdout.flush()

if __name__ == "__main__":
    main()
